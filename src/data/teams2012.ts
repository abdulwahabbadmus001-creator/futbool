function makePlayer2012(teamId: string, index: number, spec: PlayerTuple): Player {
  const [
    name,
    number,
    position,
    age,
    nationality,
    overall,
    pace,
    shooting,
    passing,
    dribbling,
    defending,
    physical,
    goalkeeping,
    archetype,
    skinTone,
  ] = spec;

  const seed = teamId.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0) + index * 19 + number;
  const parts = name.split(' ');
  const shortName = parts.length > 1 ? parts[parts.length - 1] : name;
  const marketValue = Math.max(2.0, Number((((Math.max(66, overall) - 61) ** 1.68) * 0.23).toFixed(1)));
  const wage = Math.max(12, Math.round(marketValue * 2.5));

  const attributes: PlayerAttributes = {
    pace,
    shooting,
    passing,
    dribbling,
    defending,
    physical,
    goalkeeping,
  };

  return {
    id: `${teamId}-p${index}`,
    name,
    shortName,
    number,
    position,
    nationality,
    age,
    overall,
    attributes,
    appearance: {
      skinTone,
      hairColor: HAIR_COLORS[seed % HAIR_COLORS.length],
      hairStyle: HAIR_STYLES[(seed + index) % HAIR_STYLES.length],
      bootColor: BOOT_COLORS[(seed + 2) % BOOT_COLORS.length],
    },
    marketValue,
    wage,
    contractYears: 2 + (seed % 3),
    fitness: 95 + (seed % 6),
    injuredWeeks: 0,
    archetype,
    morale: 78 + (seed % 16),
    formArrow: FORM_ARROWS[seed % FORM_ARROWS.length],
  };
}

