function buildTeam2012(bp: TeamBlueprint2012): Team {
  const roster = bp.players.map((p, idx) => makePlayer2012(bp.id, idx, p));
  const startingXI = roster.slice(0, 11).map((p) => p.id);
  const substitutes = roster.slice(11).map((p) => p.id);

  const avg = (arr: number[]) => Math.round(arr.reduce((a, b) => a + b, 0) / Math.max(1, arr.length));
  const atk = avg(roster.slice(8, 11).map((p) => p.overall));
  const mid = avg(roster.slice(5, 8).map((p) => p.overall));
  const def = avg(roster.slice(0, 5).map((p) => p.overall));

  return {
    id: bp.id,
    name: bp.name,
    shortCode: bp.shortCode,
    category: bp.category,
    leagueName: bp.leagueName,
    rating: {
      attack: atk,
      midfield: mid,
      defense: def,
      overall: Math.round((atk + mid + def) / 3),
    },
    homeKit: bp.homeKit,
    awayKit: bp.awayKit,
    altKit: bp.altKit,
    crest: bp.crest,
    tactics: {
      formationId: bp.formationId,
      attackingFormationId: bp.attackingFormationId,
      defendingFormationId: bp.defendingFormationId,
      mentality: 'balanced',
      pressing: 'medium',
      passingStyle: 'mixed',
      lineHeight: 0.54,
      compactness: 0.56,
      supportRange: 0.58,
      counterAttack: false,
      manMarking: {},
      cornerRoutine: 'standard',
      freeKickRoutine: 'direct-curl',
    },
    startingXI,
    substitutes,
    roster,
    budget: bp.budget,
  };
}

